import assert from 'node:assert/strict'
import { onlineAttention, packedRows, pageSnapshot, parallelMatrix, quantizedWeights, resourceLedger, roofline, roundEven, serviceMetrics, speculativeTrace } from '../src/lib/systems-interactive-model.ts'
const close = (a, b) => assert.ok(Math.abs(a - b) < 1e-8, `${a} != ${b}`)
const small = resourceLedger(1, 5)
assert.equal(small.weights, 744); assert.equal(small.kv, 80); assert.equal(small.linearFlops, 704); assert.equal(small.attentionFlops, 160)
assert.equal(resourceLedger(1, 4).prefillFlops, 2752)
const large = roofline(1, 8192)
assert.equal(large.kv, 1073741824); close(large.intensity, (15009316864 + 4294967296) / (15009316864 + 1073741824))
assert.ok(large.tMemory > large.tCompute)
for (const position of [3, 4, 5]) for (const block of [1, 2, 3, 4, 6]) {
  const r = onlineAttention(position, block, Math.ceil(6 / block))
  close(r.output, r.dense)
}
assert.equal(onlineAttention(5, 3, 0).output, null)
assert.deepEqual(packedRows().map(r => r.slot), [8, 9, 10, 28, 29, 36, 37, 38, 39])
assert.deepEqual(packedRows(true).map(r => r.slot), [11, 30, 40])
assert.deepEqual(packedRows(true).map(r => r.position), [3, 6, 4])
assert.equal(roundEven(1.5), 2); assert.equal(roundEven(2.5), 2); assert.equal(roundEven(-1.5), -2)
assert.deepEqual(quantizedWeights(3, 8, 20).output, [0, 20])
close(quantizedWeights(3, 4, 20).output[0], 11 / 3)
assert.equal(quantizedWeights(3, 2, 20).output[1], 21)
assert.deepEqual([8, 4, 2].map(g => quantizedWeights(3, g, 20).bytes), [5, 7, 11])
for (const mode of ['column', 'row']) {
  const r = parallelMatrix(mode); assert.deepEqual(r.output, [80, 90, 100, 110]); assert.deepEqual(r.output, r.reference)
}
const service = serviceMetrics(0.7, 0.2, 1)
assert.deepEqual(service.requests.filter(r => r.qualified).map(r => r.name), ['B', 'C'])
close(service.requests[2].tpot, 0.1); assert.equal(service.requests[1].tpot, null); assert.equal(service.requests[3].ttft, null)
assert.equal(service.requests[2].itl.length, 1); close(service.tokenGoodput, 5 / 1.5)
assert.deepEqual(speculativeTrace(0.5, 0.9, 3).submitted, [1, 2, 0, 1])
assert.deepEqual(speculativeTrace(0.5, 0.9, 3).cached, [1, 2, 0])
assert.deepEqual(speculativeTrace(0.9, 0.5, 3).cached, [1, 2])
assert.deepEqual(speculativeTrace(0.5, 0.5, 3).submitted, [1, 2, 0, 2, 2])
assert.deepEqual(speculativeTrace(0.5, 0.5, 1).cached, [1, 2, 0])
assert.deepEqual(pageSnapshot(1).refs, [2, 2, 0])
assert.deepEqual(pageSnapshot(2).aValues, [1, 2, 3, 4, 5, 6, 7])
assert.deepEqual(pageSnapshot(2).bValues, [1, 2, 3, 4, 5, 6])
assert.deepEqual(pageSnapshot(3).bValues, [1, 2, 3, 4, 5, 6, 70])
assert.deepEqual(pageSnapshot(4).free, [2]); assert.deepEqual(pageSnapshot(5).free, [0, 1, 2])
console.log('systems interactive: resource, attention, addressing, quantization, collective, service and rejection checks passed')
